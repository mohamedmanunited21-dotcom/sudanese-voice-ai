function escapeRx(s) {
  return s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

// أشكال الألف متبادلة، والتاء المربوطة/الهاء والياء/الألف المقصورة تُترك كما هي عمدًا.
function flexAlef(s) {
  return s.replace(/[أإآا]/g, '[أإآا]');
}

function stripTanween(s) {
  return s.replace(/[ً-ْ]/g, '');
}

// يبني تعبيرًا لكلمة أو عبارة كاملة. المجموعة 1 = السابقة (تُحفظ كما هي).
function wordRegex(key, opts = {}) {
  const pre = opts.prefix === 'vf' ? PREFIX_VF : PREFIX_ALL;
  let k = stripTanween(key);
  let tail = '';
  if (k.endsWith('؟')) {
    k = k.slice(0, -1);
    tail = '\\s*[؟?]?';
  }
  const body = k
    .split(/\s+/)
    .map((w) => flexAlef(escapeRx(w)))
    .join('\\s+');
  return new RegExp(`(?<![${AR_LETTERS}])(${pre})${body}${DIACRITICS}${tail}(?![${AR_LETTERS}])`, 'g');
}

// استبدال القاف→گاف من قاموس خارجي (kb.phonetic_rules.qaf_to_gaf_mapping) على الكلمة الكاملة.
function applyQafMapping(text, mapping) {
  let out = text;
  const changes = [];
  if (!mapping || typeof mapping !== 'object') return { text: out, changes };
  for (const [orig, gafWord] of Object.entries(mapping)) {
    const rx = wordRegex(orig);
    if (rx.test(out)) {
      rx.lastIndex = 0;
      out = out.replace(rx, (m, pre) => pre + gafWord);
      changes.push(`استبدال [${orig}] بـ [${gafWord}]`);
    }
  }
  return { text: out, changes };
}

const COMPILED = [...PHRASES, ...WORDS].map(([key, rep, opts]) => ({ rx: wordRegex(key, opts), rep }));

function localSudaneseNormalizer(text, kb = null) {
  let out = String(text).trim();
  const held = [];
  const hold = (s) => `${held.push(s) - 1}`;

  for (const { rx, rep } of COMPILED) {
    out = out.replace(rx, (m, pre) => pre + hold(rep));
  }

  const mapping = kb && kb.phonetic_rules && kb.phonetic_rules.qaf_to_gaf_mapping;
  if (mapping) {
    // الاستبدالات المحجوزة أعلاه لا تُمَس لأنها مخبأة خلف placeholders.
    out = applyQafMapping(out, mapping).text;
  }

  return out.replace(/(\d+)/g, (m, i) => held[Number(i)]);
}

